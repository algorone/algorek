import { NextResponse } from 'next/server';
import fs from 'fs';
import path from 'path';

export async function GET() {
  try {
    const filePath = path.join(process.cwd(), 'NOTICE.txt');
    const noticeContent = fs.readFileSync(filePath, 'utf8');

    return new NextResponse(noticeContent, {
      status: 200,
      headers: {
        'Content-Type': 'text/plain; charset=utf-8',
        'Cache-Control': 'public, max-age=86400, immutable',
      },
    });
  } catch (error) {
    return new NextResponse('Internal Server Error: NOTICE file not found', { status: 500 });
  }
}